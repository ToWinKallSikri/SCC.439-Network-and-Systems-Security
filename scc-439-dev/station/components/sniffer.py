"""
SCC.439 - Individual Programming Assessment
This class provides a network sniffer that uses the scapy library to monitor the network traffic. After the sniffing the packets are first sent to the tracker object that
organizes the sniffed packets, later the detector evaluates them. If there are any alerts generated by the detectione engine they are sent to the SIEM server through
the secure channel that ensures a protected communication. (Mutual chap - Encryption - CRC, Timestamp, HMAC check)
"""

from scapy.all import sniff


class PacketSniffer:

    def __init__(self, traffic_tracker, detection_engine, sec_channel):
        # Creating an instance of traffic tracker to collect and organize sniffed packets
        # to be then utilized by the detection engine
        self.tracker = traffic_tracker
        self.detector = detection_engine
        self.channel = sec_channel

    # Calling the function of the traffic state tracker instance to update it with the sniffed data
    # and, therefore, to organize it
    def parse_packet(self, pkt):
        self.tracker.update(pkt)
        alerts = self.detector.evaluate(self.tracker)
        # If the detector triggers on the set thresholds alerts are generated -  they are then sent to the SIEM server
        for a in alerts:
            print(f"\n[Alert GENERATED!!!!] = {a}")
            self.channel.send_alert(a)

    # Function to start the sniffing process. By default the network interfacer is set to "eth0"
    def start(self, iface="eth0", packet_count=0):
        print(f"[NIDS] Starting NIDS sniffer on {iface}...")

        try:
            # Scapy starts sniffing packets from the given network interface, sends the packets to
            # the callback funtion. Scapy will keep sniffing until it is manually interrupted
            sniff(iface=iface, prn=self.parse_packet, count=packet_count, store=False)

        except Exception as e:
            print(f"[!] Sniffer error: {e}")